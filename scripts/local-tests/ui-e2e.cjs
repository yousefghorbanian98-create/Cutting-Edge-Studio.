const chromium = require('@sparticuz/chromium').default;
const { chromium: playwright } = require('playwright');
const fs = require('fs');
const out = process.env.CE_E2E_OUTPUT || require('path').resolve(__dirname, '../../docs/evidence/local');
fs.mkdirSync(out, {recursive:true});
(async () => {
  const browser = await playwright.launch({executablePath: await chromium.executablePath(), args: chromium.args, headless: true});
  const page = await browser.newPage({viewport:{width:1920,height:1080}});
  const errors=[], requests=[], checks=[], gaps=[];
  const check=(name,ok)=>{ checks.push({name,passed:!!ok}); console.log(ok?'PASS':'FAIL',name); };
  const shot=async name=>{await page.screenshot({path:`${out}/${name}.png`,fullPage:true});};
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().includes('/api/')) requests.push({method:r.method(),url:r.url()});});
  await page.goto(process.env.CE_E2E_UI || 'http://127.0.0.1:1420');
  await page.getByText('هستهٔ پردازش متصل است', {exact:true}).waitFor();
  check('Persian RTL default',await page.locator('html').getAttribute('dir')==='rtl');
  check('Reference gate blocks next',await page.getByTestId('wizard-next').isDisabled());
  await shot('01-persian-pro');
  await page.getByRole('button',{name:'زبان',exact:true}).click();
  check('English LTR toggle',await page.locator('html').getAttribute('dir')==='ltr');
  const files = Array.from({length:10},(_,i)=>`/tmp/ce-media/clips/clip${i+1}.mp4`);
  await page.locator('input[type=file]').setInputFiles(files);
  check('10 media entries displayed',await page.locator('li[data-testid^="clip-"]').count()===10);
  await page.locator('input[type=file]').setInputFiles([files[0]]);
  check('Duplicate import gives feedback',await page.getByRole('alert').count()===1);
  await page.getByRole('button',{name:'Add to timeline clip1.mp4',exact:true}).click();
  check('Timeline receives clip',await page.locator('.timeline-editor-action').count()>0);
  await page.getByRole('button',{name:'Reference intake',exact:true}).click();
  await shot('02-english-media-timeline');
  for(let i=0;i<4;i++){await page.getByTestId('wizard-next').click();await page.waitForTimeout(220);}
  check('Wizard reaches final UI step',await page.getByTestId('wizard-next').innerText()==='Start analysis');
  const before=requests.length;
  await page.getByTestId('wizard-next').click();
  await page.waitForTimeout(500);
  if(requests.length===before) gaps.push('Start analysis changes local wizard state only; no backend analysis request.');
  await shot('03-wizard-final');
  const render=page.getByRole('button',{name:'Build preview',exact:true});
  await render.scrollIntoViewIfNeeded();
  const renderBefore=requests.length;
  await render.click(); await page.waitForTimeout(400);
  if(requests.length===renderBefore) gaps.push('Build preview button has no backend render request or visible output.');
  await page.getByRole('button',{name:'YouTube',exact:true}).click();
  check('Platform control updates summary',(await page.getByTestId('post-summary').innerText()).includes('youtube'));
  await shot('04-post-controls');
  await page.keyboard.press('Control+k');
  check('Command palette opens',await page.getByRole('combobox').count()>=1);
  await shot('05-command-palette');
  await page.getByRole('option',{name:/Switch theme/}).click();
  check('Glass theme applies',await page.locator('html').getAttribute('data-theme')==='glass');
  await shot('06-glass-theme');
  await page.keyboard.press('Control+k');
  await page.getByRole('option',{name:/Switch theme/}).click();
  check('Minimal theme applies',await page.locator('html').getAttribute('data-theme')==='minimal');
  await shot('07-minimal-theme');
  check('No browser page errors',errors.length===0);
  gaps.push('Media import is frontend metadata only; file paths are browser file names, not backend asset imports.');
  gaps.push('Preview panel remains a placeholder; this is not a complete desktop editing E2E.');
  fs.writeFileSync(`${out}/ui-results.json`,JSON.stringify({checks,gaps,errors,requests},null,2));
  console.log(JSON.stringify({checks,gaps,errors},null,2));
  await browser.close();
  process.exitCode = checks.every(c=>c.passed) ? 0 : 1;
})().catch(e=>{console.error(e);process.exit(1);});
